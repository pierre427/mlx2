@pytest.fixture(scope="module")
def fast_dir(tmp_path_factory):
    if MODEL_DIR is None:
        pytest.skip("Xing4.0 tokenizer.model not available")
    conv = _converter()
    model = conv.read_spm_model(MODEL_DIR / "tokenizer.model")
    conv.validate_spm(model)
    out = tmp_path_factory.mktemp("xing_fast")
    conv.build_tokenizer(model).save(str(out / "tokenizer.json"))
    reference_config = MODEL_DIR / "tokenizer_config.reference.json"
    if not reference_config.exists():
        reference_config = MODEL_DIR / "tokenizer_config.json"
    config = json.loads(reference_config.read_text())
    (out / "tokenizer_config.json").write_text(json.dumps(xt.fast_tokenizer_config(config)))
    shutil.copy2(MODEL_DIR / "tokenizer.model", out / "tokenizer.model")
    if (MODEL_DIR / "chat_template.jinja").exists():
        shutil.copy2(MODEL_DIR / "chat_template.jinja", out / "chat_template.jinja")
    return out


@needs_model
def test_fast_encode_matches_reference_fixture(fast_dir):
    tokenizer = xt.load_fast_unverified(fast_dir)
    texts = [case["text"] for case in FIXTURE["encode"]]
    batch = tokenizer(texts, add_special_tokens=False)["input_ids"]
    for case, ids in zip(FIXTURE["encode"], batch):
        assert ids == case["ids"], case["text"]
        assert tokenizer.encode(case["text"]) == case["ids"]  # add_bos_token is false


@needs_model
def test_fast_decode_matches_reference_fixture(fast_dir):
    tokenizer = xt.load_fast_unverified(fast_dir)
    for case in FIXTURE["decode"]:
        assert tokenizer.decode(case["ids"]) == case["text"]
        assert tokenizer.decode(case["ids"], skip_special_tokens=True) == case["text_skip_special"]
    for key, piece in FIXTURE["pieces"].items():
        assert tokenizer.convert_ids_to_tokens(int(key)) == piece


@needs_model
def test_render_prompt_matches_reference_chat_template(fast_dir):
    if not (fast_dir / "chat_template.jinja").exists():
        pytest.skip("chat_template.jinja not available")
    tokenizer = xt.load_fast_unverified(fast_dir)
    wrapper = xt.make_tokenizer_wrapper(tokenizer)
    for case in FIXTURE["chat"]:
        tools = case["tools"] or None
        text = tokenizer.apply_chat_template(case["messages"], tools=tools, tokenize=False,
                                             add_generation_prompt=True, enable_thinking=case["enable_thinking"])
        assert text == case["text"]
        assert xt.render_prompt(tokenizer, case["messages"], tools, case["enable_thinking"]) == case["ids"]
        assert xt.render_prompt(wrapper, case["messages"], tools, case["enable_thinking"]) == case["ids"]
    on = xt.render_prompt(tokenizer, [{"role": "user", "content": "Hi"}], None, True)
    off = xt.render_prompt(tokenizer, [{"role": "user", "content": "Hi"}], None, False)
    assert on[-3:] == [xt.THINK_START_ID, xt.SPIECE_ID, 35]  # <think> ▁ \n
    assert off[-1] == xt.THINK_END_ID


@needs_model
def test_stamped_load_and_wrapper_route(fast_dir):
    report = {"status": "pass", "counts": {"fuzz_strings": 20000}, "seed": 0}
    if not (fast_dir / "chat_template.jinja").exists():
        pytest.skip("chat_template.jinja not available")
    stamp = xt.make_stamp(fast_dir, report=report, versions={}, generated_at="test")
    (fast_dir / xt.STAMP_NAME).write_text(json.dumps(stamp))
    tokenizer, receipt = xt.load_tokenizer(fast_dir)
    assert receipt["route"] == "fast-tokenizer-json" and receipt["trust_remote_code"] is False
    wrapper = xt.make_tokenizer_wrapper(tokenizer)
    assert wrapper.think_start_id == 9 and wrapper.think_end_id == 10
    assert wrapper.eos_token_ids == {2}
    text = "Reasoning 步骤 1 😀\n</think>Answer: 42<tool_call>f<param_key>x</param_key><param_value>1</param_value></tool_call>"
    ids = tokenizer.encode(text, add_special_tokens=False)
    detok = wrapper.detokenizer
    for token in ids:
        detok.add_token(token)
    detok.finalize()
    assert detok.text == tokenizer.decode(ids) == text
    (fast_dir / "tokenizer.json").write_text((fast_dir / "tokenizer.json").read_text() + " ")
    with pytest.raises(xt.XingTokenizerError):
        xt.load_tokenizer(fast_dir)
