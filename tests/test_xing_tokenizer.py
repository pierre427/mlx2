def _fake_stamped_dir(tmp_path: Path) -> Path:
    for name in xt.STAMPED_FILES:
        (tmp_path / name).write_text(name)
    report = {"status": "pass", "counts": {"fuzz_strings": 20000}, "seed": 1}
    stamp = xt.make_stamp(tmp_path, report=report, versions={}, generated_at="now")
    (tmp_path / xt.STAMP_NAME).write_text(json.dumps(stamp))
    return tmp_path


def test_stamp_verification_fails_closed(tmp_path):
    with pytest.raises(xt.XingTokenizerError, match="no tokenizer parity stamp"):
        xt.verify_parity_stamp(tmp_path)
    artifact = _fake_stamped_dir(tmp_path)
    assert xt.verify_parity_stamp(artifact)["status"] == "pass"
    (artifact / "tokenizer.json").write_text("tampered")
    with pytest.raises(xt.XingTokenizerError, match="changed since"):
        xt.verify_parity_stamp(artifact)


def test_stamp_rejects_failed_or_undersized_runs(tmp_path):
    artifact = _fake_stamped_dir(tmp_path)
    stamp = json.loads((artifact / xt.STAMP_NAME).read_text())
    for patch in ({"status": "fail"}, {"counts": {"fuzz_strings": 10}}, {"schema": "other"}):
        (artifact / xt.STAMP_NAME).write_text(json.dumps({**stamp, **patch}))
        with pytest.raises(xt.XingTokenizerError):
            xt.verify_parity_stamp(artifact)


def test_loader_without_stamp_fails_closed_unless_fallback_enabled(tmp_path):
    with pytest.raises(xt.XingTokenizerError):
        xt.load_tokenizer(tmp_path)
    # Opt-in fallback still needs the reference code; it does not silently
    # degrade to anything else.
    with pytest.raises(xt.XingTokenizerError):
        xt.load_tokenizer(tmp_path, allow_reference_fallback=True)


def test_fast_tokenizer_config_drops_remote_code():
    reference = {"tokenizer_class": "Xing4_0Tokenizer", "auto_map": {"AutoTokenizer": ["x", None]},
                 "add_bos_token": False, "sp_model_kwargs": {}, "eos_token": "<_end>"}
    config = xt.fast_tokenizer_config(reference)
    assert config["tokenizer_class"] == "TokenizersBackend"
    assert "auto_map" not in config and "sp_model_kwargs" not in config
    assert config["eos_token"] == "<_end>" and config["add_bos_token"] is False


def test_normalize_messages_parses_openai_tool_arguments():
    messages = [
        {"role": "assistant", "content": "", "tool_calls": [
            {"id": "c1", "type": "function", "function": {"name": "f", "arguments": "{\"a\": 1}"}}]},
        {"role": "tool", "content": [{"output": "x"}]},
    ]
    out = xt.normalize_messages(messages)
    assert out[0]["tool_calls"][0]["function"]["arguments"] == {"a": 1}
    assert messages[0]["tool_calls"][0]["function"]["arguments"] == "{\"a\": 1}"
    with pytest.raises(TypeError):
        xt.normalize_messages([{"role": "assistant", "tool_calls": [{"function": {"name": "f", "arguments": "[1]"}}]}])
    with pytest.raises(ValueError):
        xt.normalize_messages([{"role": "user", "content": [{"type": "image_url", "image_url": {}}]}])


def test_converter_user_defined_pattern_is_leftmost_longest():
    import re

    conv = _converter()
    pattern = re.compile(conv.user_defined_pattern(["_", "__", "___", "____", "1", "\n", "<reserve1>", "<reserve10>"]))
    assert pattern.findall("a_____b<reserve10>\n1") == ["____", "_", "<reserve10>", "\n", "1"]


