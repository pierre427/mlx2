def test_fixture_decodes_match_reference_both_skip_modes():
    tables = _fixture_tables()
    assert len(FIXTURE["decode"]) >= 200
    for case in FIXTURE["decode"]:
        assert xt.decode_ids(tables, case["ids"]) == case["text"], case["ids"]
        assert xt.decode_ids(tables, case["ids"], True) == case["text_skip_special"], case["ids"]


def test_streaming_detokenizer_equals_full_decode_at_every_step():
    tables = _fixture_tables()
    for case in FIXTURE["decode"]:
        detok = xt.XingStreamingDetokenizer(_TablesOnly(tables))
        emitted = ""
        for index, token in enumerate(case["ids"]):
            detok.add_token(token)
            emitted += detok.last_segment
            # Everything emitted so far is final: a prefix of the full decode.
            assert case["text"].startswith(emitted)
            full_prefix = xt.decode_ids(tables, case["ids"][: index + 1])
            assert full_prefix.startswith(emitted)
        detok.finalize()
        emitted += detok.last_segment
        assert emitted == detok.text == case["text"]


def test_decode_rules_reproduce_sentencepiece_quirks():
    tables = _fixture_tables()
    w, ww = xt.SPIECE_ID, 396  # "▁", "▁▁"
    hi = 13029  # "▁hi"
    assert tables.pieces[hi] == "▁hi" and tables.pieces[ww] == "▁▁"
    byte = lambda b: xt.BYTE_OFFSET + b  # noqa: E731
    cases = {
        (4, hi): "<_user>hi",  # one leading ▁ stripped per run after a special
        (hi, hi): "hi hi",
        (w, hi): " hi",  # a lone ▁ is the consumed prefix; the next keeps its space
        (7, hi): "hi",  # unregistered control: "" and keeps the expectation
        (w, 7, hi): " hi",
        (0, hi): " ⁇  hi",  # <_unk>
        (byte(0xF0), byte(0x9F), hi): "�� hi",  # one U+FFFD per invalid byte
        (byte(0xF0), byte(0x9F), byte(0x98), byte(0x80)): "\U0001F600",
        (byte(0xF0), 7, byte(0x9F)): "��",  # a control piece splits byte runs
        (byte(0x20), hi): "  hi",
        (ww,): " ",
        (10, ww, 11): "</think> <tool_call>",
    }
    for ids, want in cases.items():
        assert xt.decode_ids(tables, list(ids)) == want, ids
    # skip_special_tokens removes specials first, so runs merge.
    assert xt.decode_ids(tables, [4, hi, 5, hi], True) == "hi hi"
    assert xt.decode_ids(tables, [4, hi, 5, hi]) == "<_user>hi<_bot>hi"
    with pytest.raises(IndexError):
        xt.decode_ids(tables, [xt.VOCAB_SIZE])


def test_streaming_random_sequences_match_full_decode():
    tables = _fixture_tables()
    rng = random.Random(3)
    pool = [int(k) for k in FIXTURE["pieces"]]
    for _ in range(2000):
        ids = [rng.choice(pool) for _ in range(rng.randint(0, 30))]
        detok = xt.XingStreamingDetokenizer(_TablesOnly(tables))
        for token in ids:
            detok.add_token(token)
        detok.finalize()
        assert detok.text == xt.decode_ids(tables, ids)


def test_streaming_rejects_a_padded_logits_id_with_a_value_error():
    """The logits row is wider than the vocabulary; a padded id is a caller
    error reported like the BPE detokenizer's, and leaves the stream intact."""
    detok = xt.XingStreamingDetokenizer(_TablesOnly(_fixture_tables()))
    hi = 13029  # "▁hi"
    detok.add_token(hi)
    for bad in (xt.VOCAB_SIZE, xt.VOCAB_SIZE + 7, -1):
        with pytest.raises(ValueError, match="unknown Xing4.0 token ID"):
            detok.add_token(bad)
    detok.finalize()
    assert detok.tokens == [hi]
    assert detok.text == xt.decode_ids(_fixture_tables(), [hi])


def test_tables_reject_a_foreign_vocabulary():
    pieces = [f"p{i}" for i in range(xt.VOCAB_SIZE)]
    with pytest.raises(xt.XingTokenizerError):
        xt._Tables(pieces)


