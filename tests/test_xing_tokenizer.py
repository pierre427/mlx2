"""Xing4.0 tokenizer: exact reference decode, streaming, stamp, and fast-build parity.

Model-free tests use the committed reference fixture
(``tests/fixtures/xing4_0_tokenizer/expected.json``, generated by
``scripts/xing4_0_tokenizer.py --write-fixture`` from the slow
``Xing4_0Tokenizer``).  Tests that build ``tokenizer.json`` need the 2.2 MB
``tokenizer.model``: set ``XING4_0_TOKENIZER_DIR`` to a directory holding it
(and ``chat_template.jinja``) or install the artifact under
``~/mlx-models/Xing4.0-*``; they skip cleanly otherwise.
"""

from __future__ import annotations

import importlib.util
import json
import os
import random
import shutil
from pathlib import Path

import pytest

from mlx2.adapters import xing_tokenizer as xt

ROOT = Path(__file__).resolve().parents[1]
FIXTURE = json.loads((ROOT / "tests/fixtures/xing4_0_tokenizer/expected.json").read_text())


def _converter():
    spec = importlib.util.spec_from_file_location("xing4_0_tokenizer_script", ROOT / "scripts/xing4_0_tokenizer.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _fixture_tables() -> xt._Tables:
    """The fixed Xing4.0 layout plus every real piece the fixture touches."""
    pieces = [f"▁filler{i}" for i in range(xt.VOCAB_SIZE)]
    for key, piece in FIXTURE["pieces"].items():
        pieces[int(key)] = piece
    return xt._Tables(pieces)


class _TablesOnly:
    def __init__(self, tables):
        self._xing_tables = tables


def _model_dir() -> Path | None:
    candidates = []
    if os.environ.get("XING4_0_TOKENIZER_DIR"):
        candidates.append(Path(os.environ["XING4_0_TOKENIZER_DIR"]))
    candidates += sorted(Path.home().glob("mlx-models/Xing4.0-*"))
    for candidate in candidates:
        model = candidate / "tokenizer.model"
        if model.exists() and xt.sha256_file(model) == FIXTURE["tokenizer_model_sha256"]:
            return candidate
    return None


MODEL_DIR = _model_dir()
needs_model = pytest.mark.skipif(MODEL_DIR is None, reason="Xing4.0 tokenizer.model not available")


