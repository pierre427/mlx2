#!/usr/bin/env python3
"""Native synthetic qualifier for the approximate tensor-API attention research candidate.

Scope: synthetic primitive approximate DENSE attention only (B1, materialized
float16 KV) for ``mlx2.adapters.tensor_fa_research``. Not recurrent state,
prefix cache, model, ragged batch, MTP acceptance, serving or end-to-end
gain. A pass here is a native synthetic gate, never qualification or
selection; ``qualified``/``selected``/``model_gain`` are always false.

Evidence vs execution: ``evaluate()`` judges supplied evidence (dicts, JSON)
and can NEVER establish native execution, whatever the evidence says. Only
the live in-process run object built by ``_run_native`` (after source/build
admission, with the real ``NativeBackend`` and its counters) can stamp
``native_synthetic_gate``; a JSON round trip drops it. This is a trust
boundary against forged reports and fake backends, not a security claim
against arbitrary code that monkeypatches this module.

Identity association: the native backend class, the live-run type, the
witness and the evaluator are captured ONCE, at import, in the closure that
defines ``_run_native`` and ``native_verdict`` (not in default arguments a
caller could override). Rebinding the module names ``NativeBackend``,
``_LiveNativeRun``, ``_WITNESS`` or ``evaluate`` afterwards, a subclass or a
look-alike cannot make a CPU fake count as native, and ``_run_native`` still
constructs the original class. Evidence-association hygiene only: it does
not resist code that edits closures, class attributes or private objects.

Timing is NOT implemented: ``--timing`` is refused before any admission or
backend work. Controlled fair kernel/conversion timing is a pending stage.

Two references, never mixed:
  * host: independent float64 stable softmax over exactly the visible keys,
    regenerated by the evaluator from the catalogue seed. It validates the
    inputs, masks, witnesses and stub evidence; it is not native fidelity.
  * native: ``mx.fast.scaled_dot_product_attention`` on the same visible keys
    with native GQA (un-tiled KV heads) in float16. SDPA needs one dtype for
    q/k/v, so for float32-query cells this baseline rounds q DOWN to float16
    (the two arms do not share query precision); the host float64 reference
    uses the actual q, and a float32 native SDPA run is a diagnostic only.
    The candidate's ``reference_attention`` (repeats KV to Hq, casts fp32) is
    never used.

Nothing imports MLX at module import, ``--help``, ``--catalogue`` or
admission. ``--run-native`` requires ``--i-own-the-gpu`` (an acknowledgement,
NOT ownership: the parent wrapper /tmp/mlx2-intake/stage3_gpu.py owns the CPG
lease and both flocks), ``--source-root`` equal to this checkout, and
``--source-commit`` equal to MLX2_INTAKE_SOURCE_COMMIT and git HEAD. Before
any MLX import: a clean tracked+untracked status for src/scripts/tests/
provenance, every bound file's hash equal to its blob at HEAD, and the
installed MLX core extension, libmlx and metallib hashed. After importing MLX
and before any device query, the imported extension (``mx.__file__``) and
``mx.__version__`` must match that snapshot. Before EVERY backend dispatch
the bound source and MLX files must still equal the admitted snapshot (the
run stops otherwise), and after the run HEAD, clean status, hashes, build
and module paths are re-checked. No CPU fallback. A receipt is written only
with ``--out`` (exclusive creation) after a completed run.

  # run from this checkout; the isolated worktree has no .venv, and the parent wrapper's
  # source-root and CPG workflow/task defaults are obsolete, so all four are explicit:
  MLX2_INTAKE_SOURCE_ROOT=<this checkout> MLX2_INTAKE_SOURCE_COMMIT=<full HEAD sha> \\
  MLX2_INTAKE_CPG_WORKFLOW=<fresh live workflow> MLX2_INTAKE_CPG_TASK=<fresh native task> \\
  python /tmp/mlx2-intake/stage3_gpu.py tensor-fa-native \\
      ~/Desktop/mlx2/.venv/bin/python scripts/qualify_tensor_fa_research.py \\
      --run-native --i-own-the-gpu --source-root <this checkout> --source-commit <full HEAD sha> \\
      --out <new receipt>.json
"""

