def _jsonable(report):
    import numpy as np

    def clean(x):
        if isinstance(x, np.ndarray):
            return {"dtype": str(x.dtype), "shape": list(x.shape), "sha256": hashlib.sha256(x.tobytes()).hexdigest()}
        if isinstance(x, dict):
            return {k: clean(v) for k, v in x.items()}
        if isinstance(x, list):
            return [clean(v) for v in x]
        return x

    return clean(report)


def main(argv=None, environ=None):
    args = build_parser().parse_args(argv)
    environ = os.environ if environ is None else environ
    if args.catalogue:
        print(json.dumps({"mandatory": MANDATORY, "catalogue_only_optional": TIMING_CELLS, "cases": CATALOGUE},
                         indent=1))
        return 0
    try:
        if args.timing:                                              # before any admission/backend/device work
            raise Refused("timing is not implemented: controlled fair kernel/conversion timing is a pending stage")
        cases, full = select_cases(args.cases)
        admission = native_admission(args, environ)                 # before any MLX import
        live = _run_native(admission, cases, full)
        native = native_verdict(live)                               # evaluation bound to this live run
        evaluation = native.pop("evaluation")
    except Refused as error:
        print(json.dumps({"verdict": "refused", "refusals": [str(error)], "native_synthetic_gate": False,
                          "qualified": False, "selected": False, "model_gain": False}))
        return 1
    receipt = {"schema": SCHEMA, "scope": SCOPE, "tolerance": TOLERANCE, "evaluation": evaluation,
               "native_execution": native, "report": _jsonable(live.report),
               "qualified": False, "selected": False, "model_gain": False,
               "note": "native_execution was stamped in-process; re-evaluating this JSON can never re-establish it"}
    with open(args.out, "x") as handle:                              # exclusive creation, completed runs only
        json.dump(receipt, handle, indent=1)
    print(json.dumps({"verdict": evaluation["verdict"], **native}))
    return 0 if native["native_synthetic_gate"] else 1


