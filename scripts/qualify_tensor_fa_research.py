# ================================================================ catalogue (pure)

def _case(cid, dim, q_dtype, hq, hkv, length, kv_len, causal, q_start, law, expect="pass", optional=False):
    blocks = -(-length // Q_ROWS)
    kv_end = [min(kv_len, -(-(q_start + min((b + 1) * Q_ROWS, length)) // C_KEYS) * C_KEYS) if causal else kv_len
              for b in range(blocks)]
    qb = 4 if q_dtype == "float32" else 2
    memory = {  # bytes held at once in one native cell (inputs, f32 diagnostic copies, three outputs)
        "inputs": hq * length * dim * qb + 2 * hkv * kv_len * dim * 2,
        "f32_diagnostic_inputs": (hq * length + 2 * hkv * kv_len) * dim * 4,
        "outputs": hq * length * dim * (4 + 2 + 4),
    }
    memory["total"] = sum(memory.values())
    return {"id": cid, "dim": dim, "q_dtype": q_dtype, "hq": hq, "hkv": hkv, "length": length, "kv_len": kv_len,
            "causal": causal, "q_start": q_start, "law": law, "expect": expect, "optional": optional,
            "scale": 1.0 / math.sqrt(dim), "expected_threadgroups": blocks * hq, "kv_end": kv_end,
            "expected_memory_bytes": memory}


