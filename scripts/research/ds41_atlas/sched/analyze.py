#!/usr/bin/env python3
"""Turn sweep_*.json into markdown tables (heldout unless stated). Writes tables.md (atomic)."""
import json
import os
from collections import defaultdict

import numpy as np

from common import OUT, provenance

BOUND = {"belady/none": "bound", "belady/oracle_xtok": "bound", "lru/oracle_d1": "bound", "lru/oracle_xtok": "bound",
         "lru/h2+d1": "upper bound (draft=truth)", "lru/h3+d1": "upper bound (draft=truth)"}


def label(sim):
    pol, pf = sim.get("policy", "lru"), sim.get("prefetch", "none")
    s = f"{pol}/{pf}"
    if pf != "none" and not pf.startswith("oracle"):
        s += f" k={sim.get('k', 8)}"
        if sim.get("prio", "value") != "value":
            s += f" {sim['prio']}"
        if sim.get("theta_mult", 1.0) not in (1.0, 0.0):
            s += f" th={sim['theta_mult']}"
    if sim.get("gds_cap", 1e9) < 1e9:
        s += f" cap={sim['gds_cap']:g}"
    if sim.get("nextuse_model"):
        s += f" {sim['nextuse_model']}"
    if sim.get("prefetch_max_ms", 1e9) < 1e9:
        s += f" pf<={sim['prefetch_max_ms']:g}ms"
    if sim.get("pin_layers"):
        s += f" pin={sim['pin_layers']}"
    if sim.get("m3ram_tier"):
        s += " +m3ram"
    return s


def load(stage):
    p = f"{OUT}/sweep_{stage}.json"
    return json.load(open(p))["runs"] if os.path.exists(p) else []


def ms(x):
    return f"{x * 1e3:.1f}"


def grid_tables(runs, parse):
    cells = sorted({(r["sim"]["ram_gb"], r["cfg_over"]["compute"]) for r in runs if r["cfg_over"]["parse"] == parse})
    pols = defaultdict(dict)
    for r in runs:
        if r["cfg_over"]["parse"] != parse:
            continue
        cell = (r["sim"]["ram_gb"], r["cfg_over"]["compute"])
        pols[label(r["sim"])][cell] = r["result"]
    # rank by mean heldout overhead across cells (normalised by LRU/none in each cell)
    def rel(lbl):
        return np.mean([pols[lbl][c]["heldout"]["overhead_s_per_token"] / max(1e-9, pols["lru/none"][c]["heldout"]["overhead_s_per_token"])
                        for c in cells if c in pols[lbl]])
    order = sorted(pols, key=rel)
    lines = [f"\n#### parse={parse}: heldout overhead ms/token (stall + GPU steal) / misses per token; mean ratio vs LRU\n"]
    hdr = "| policy | " + " | ".join(f"{g}GB/{c}ms" for g, c in cells) + " | mean vs LRU | kind |"
    lines += [hdr, "|" + "---|" * (len(cells) + 3)]
    for lbl in order:
        row = []
        for c in cells:
            h = pols[lbl].get(c, {}).get("heldout")
            row.append("-" if not h else f"{ms(h['overhead_s_per_token'])} / {h['misses_per_token']:.1f}")
        kind = next((v for k, v in BOUND.items() if lbl.startswith(k)), "")
        lines.append(f"| {lbl} | " + " | ".join(row) + f" | {rel(lbl):.2f} | {kind} |")
    return lines, order, pols, cells


def main():
    out = ["# tables (generated by analyze.py; heldout requests unless stated)\n"]
    tune = load("tune")
    if tune:
        out.append("\n### tune (TRAIN requests, compute 12 ms, 75 GB): best 25 by train s/token per parse\n")
        for parse in ("low", "high"):
            rs = sorted([r for r in tune if r["cfg_over"].get("parse") == parse], key=lambda r: r["result"]["train"]["s_per_token"])
            out += [f"\nparse={parse}\n", "| config | train s/tok | train overhead ms | heldout overhead ms | misses/tok (ho) | prefetch loads/tok | used/tok |",
                    "|---|---|---|---|---|---|---|"]
            for r in rs[:25]:
                tr, ho, al = r["result"]["train"], r["result"]["heldout"], r["result"]["all"]
                out.append(f"| {label(r['sim'])} | {tr['s_per_token']:.4f} | {ms(tr['overhead_s_per_token'])} | {ms(ho['overhead_s_per_token'])} | "
                           f"{ho['misses_per_token']:.1f} | {al['loads_prefetch_per_token']:.1f} | {al['pref_used_per_token']:.1f} |")
    grid = load("grid")
    if grid:
        out.append("\n### grid\n")
        for parse in ("low", "high"):
            lines, order, pols, cells = grid_tables(grid, parse)
            out += lines
            # utilisation / prefetch traffic at 75GB 12ms
            c = (75, 12)
            out += [f"\nparse={parse}, 75 GB / 12 ms detail (heldout s/token, stall, steal; prefetch traffic all tokens)\n",
                    "| policy | s/token | stall ms | steal ms | misses | inflight-hit misses | prefetch loads/tok | used | wasted | nvme util |",
                    "|---|---|---|---|---|---|---|---|---|---|"]
            for lbl in order:
                r = pols[lbl].get(c)
                if not r:
                    continue
                h, a = r["heldout"], r["all"]
                out.append(f"| {lbl} | {h['s_per_token']:.4f} | {ms(h['stall_s_per_token'])} | {ms(h['steal_s_per_token'])} | "
                           f"{h['misses_per_token']:.1f} | {h['miss_inflight']:.1f} | {a['loads_prefetch_per_token']:.1f} | "
                           f"{a['pref_used_per_token']:.1f} | {a['pref_wasted_per_token']:.1f} | {a['util']['nvme']:.3f} |")
    t7 = load("t7")
    if t7:
        out += ["\n### T7 subset (compute 12 ms, parse low): heldout s/token | misses nvme/t7/m3ram per token\n",
                "| ram | t7 MB/s | nvme frac | policy | s/token | overhead ms | miss nvme | miss t7 | miss m3ram | train s/token |",
                "|---|---|---|---|---|---|---|---|---|---|"]
        for r in sorted(t7, key=lambda r: (r["sim"]["ram_gb"], r["cfg_over"]["t7_bw"], r["sim"]["nvme_frac"],
                                           r["result"]["heldout"]["s_per_token"])):
            h = r["result"]["heldout"]
            out.append(f"| {r['sim']['ram_gb']} | {r['cfg_over']['t7_bw'] * 1e3:.0f} | {r['sim']['nvme_frac']} | {label(r['sim'])} | "
                       f"{h['s_per_token']:.3f} | {ms(h['overhead_s_per_token'])} | {h['miss_nvme']:.1f} | {h['miss_t7']:.2f} | "
                       f"{h['miss_m3ram']:.2f} | {r['result']['train']['s_per_token']:.3f} |")
    pipe = load("pipeline")
    if pipe:
        out += ["\n### pipeline placements (compute 12 ms on M5): heldout s/token\n",
                "| placement | ram | state | remote factor | policy | s/token | overhead ms | hop ms | remote extra ms | stall ms | misses |",
                "|---|---|---|---|---|---|---|---|---|---|---|"]
        for r in sorted(pipe, key=lambda r: (r.get("t7", False), r["sim"]["ram_gb"], r["result"]["heldout"]["s_per_token"])):
            h = r["result"]["heldout"]
            out.append(f"| {r['placement']}{' (T7 45MB/s)' if r.get('t7') else ''} | {r['sim']['ram_gb']} | {r['sim'].get('remote_state', 'idle')} | "
                       f"{r['cfg_over'].get('m3_factor')} | {label(r['sim'])} | {h['s_per_token']:.4f} | {ms(h['overhead_s_per_token'])} | "
                       f"{ms(h['hop_s_per_token'])} | {ms(h['remote_extra_s_per_token'])} | {ms(h['stall_s_per_token'])} | {h['misses_per_token']:.1f} |")
    sens = load("sens")
    if sens:
        out += ["\n### sensitivity (75 GB, 12 ms): heldout overhead ms/token\n"]
        cells = sorted({(r["cfg_over"]["nvme_bw"], r["cfg_over"]["router_frac"]) for r in sens})
        pols = defaultdict(dict)
        for r in sens:
            pols[label(r["sim"])][(r["cfg_over"]["nvme_bw"], r["cfg_over"]["router_frac"])] = r["result"]["heldout"]
        out += ["| policy | " + " | ".join(f"nvme {b}GB/s rf {f}" for b, f in cells) + " |", "|" + "---|" * (len(cells) + 1)]
        for lbl in sorted(pols):
            out.append(f"| {lbl} | " + " | ".join(ms(pols[lbl][c]["overhead_s_per_token"]) if c in pols[lbl] else "-" for c in cells) + " |")
    for stage, title in (("extra", "pinned early layers (75/40/90 GB, 12 ms, parse low)"),
                         ("t7b", "T7 follow-up: tier-restricted prefetch (75 GB, T7 45 MB/s, 12 ms)")):
        rs = load(stage)
        if not rs:
            continue
        out += [f"\n### {title}: heldout\n", "| ram | nvme frac | policy | s/token | overhead ms | misses | miss t7 | miss m3ram | train s/token |",
                "|---|---|---|---|---|---|---|---|---|"]
        for r in sorted(rs, key=lambda r: (r["sim"]["ram_gb"], r["sim"].get("nvme_frac", 1), r["sim"].get("m3ram_tier", False),
                                           r["result"]["heldout"]["s_per_token"])):
            h = r["result"]["heldout"]
            out.append(f"| {r['sim']['ram_gb']} | {r['sim'].get('nvme_frac', 1.0) if r['sim'].get('t7_subset') else 1.0} | {label(r['sim'])} | "
                       f"{h['s_per_token']:.3f} | {ms(h['overhead_s_per_token'])} | {h['misses_per_token']:.1f} | {h['miss_t7']:.3f} | "
                       f"{h['miss_m3ram']:.2f} | {r['result']['train']['s_per_token']:.3f} |")
    txt = "\n".join(out) + "\n\n<!-- " + json.dumps(provenance()) + " -->\n"
    tmp = f"{OUT}/tables.md.tmp"
    open(tmp, "w").write(txt)
    os.replace(tmp, f"{OUT}/tables.md")
    print(txt[:3000])


if __name__ == "__main__":
    main()
