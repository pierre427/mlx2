#!/usr/bin/env python3
"""Generate the creative cells of English core corpus v2 with Artemis-31B-v1.2 (Pierre approved one window,
2026-11-14). Runs INSIDE an owned GPU window (amoeba_topics_window.sh: CPG lease, paired locks, :8282 paused).

1. Start an mlx2 dev server on --port (default 8393) with --ordinary and 4 lanes, in its own process group,
   with a footprint watchdog (--cap-gb, default 55): over it, the server is stopped.
2. Load check: 3 prompts; abort (exit 4) if any reply is empty, garbled (mostly non-letters, long repeats) or
   shows thinking text.
3. Generate every prompt (4 in flight), thinking off, conservative sampling (recorded). Rows stream to
   OUT/generated.jsonl (resumable). Every text is labelled model-generated by Artemis.
4. Always stop the server in finally. Receipt: OUT/receipt.json (checkpoint, fingerprint, mlx2 commit, sampling,
   server command, load time, peak footprint, counts).
"""
from __future__ import annotations

import argparse
import concurrent.futures as cf
import json
import os
import re
import signal
import subprocess
import sys
import threading
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
SAMPLING = {"temperature": 0.7, "top_p": 0.9, "repetition_penalty": 1.05, "max_tokens": 400}


def get(base, path):
    with urllib.request.urlopen(base + path, timeout=30) as r:
        return json.loads(r.read())


def post(base, body, timeout=600):
    rq = urllib.request.Request(base + "/v1/chat/completions", data=json.dumps(body).encode(),
                                headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(rq, timeout=timeout) as r:
        return json.loads(r.read())


def garbled(t):
    if not t or len(t.strip()) < 80:
        return "empty or too short"
    letters = sum(c.isalpha() for c in t) / max(1, len(t))
    if letters < 0.6:
        return f"letters fraction {letters:.2f}"
    if re.search(r"(.{6,40})\1{4,}", t, re.S):
        return "long repeated span"
    if re.search(r"<think|thinking process|^thought:", t, re.I):
        return "thinking text"
    return None


def main():
    import amoeba27b_lib as A
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default=str(Path.home() / "mlx-models/Artemis-31B-v1.2-q8-mlx2"))
    ap.add_argument("--prompts", default=str(ROOT / "docs/research/amoeba-topics/core-corpus-v2-generation/prompts.jsonl"))
    ap.add_argument("--out", required=True)
    ap.add_argument("--port", type=int, default=8393)
    ap.add_argument("--lanes", type=int, default=4)
    ap.add_argument("--cap-gb", type=float, default=55)
    ap.add_argument("--limit", type=int, default=0)
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    logf = open(out / "run.log", "a")

    def log(m):
        line = f"{time.strftime('%H:%M:%S')} {m}"
        print(line, flush=True)
        logf.write(line + "\n")
        logf.flush()
    from mlx2.adapters.registry import inspect_model
    ident = inspect_model(Path(args.model)).artifact
    ckpt = f"{Path(args.model).name}@{ident['fingerprint'][:8]}"
    rev = subprocess.run(["git", "rev-parse", "--short=9", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    base = f"http://127.0.0.1:{args.port}"
    cmd = [sys.executable, "-m", "mlx2.server", "--model", args.model, "--port", str(args.port), "--ordinary",
           "--max-lanes", str(args.lanes), "--max-inflight", str(args.lanes)]
    rec = {"schema": "mlx2.amoeba-corev2-generation.v1", "checkpoint": ckpt, "fingerprint": ident["fingerprint"],
           "source_revision": ident.get("source_revision"), "mlx2_source_revision": rev, "sampling": SAMPLING,
           "thinking": "off (enable_thinking false, reasoning_effort none)", "server_cmd": cmd,
           "approved": "Pierre 2026-11-14 ('Approve'), one window", "label": "model-generated by Artemis-31B-v1.2 (Gemma terms)",
           "qualification": "unqualified"}
    slog = open(out / "server.log", "a")
    env = dict(os.environ)
    # Serve this checkout's mlx2, not whatever an ambient PYTHONPATH (or the
    # editable install) points at; keep the caller's entries after it.
    env["PYTHONPATH"] = os.pathsep.join(
        [str(ROOT / "src")] + [p for p in os.environ.get("PYTHONPATH", "").split(os.pathsep) if p])
    proc = subprocess.Popen(cmd, cwd=ROOT, env=env, stdout=slog, stderr=subprocess.STDOUT, start_new_session=True)
    peak = {"gb": 0.0}
    stop_ev = threading.Event()

    def stop():
        if proc.poll() is None:
            os.killpg(proc.pid, signal.SIGTERM)
            try:
                proc.wait(timeout=90)
            except subprocess.TimeoutExpired:
                os.killpg(proc.pid, signal.SIGKILL)
                proc.wait(timeout=30)

    def watch():
        while not stop_ev.is_set():
            g = A.footprint_gb(proc.pid)
            if g:
                peak["gb"] = max(peak["gb"], g)
                if g > args.cap_gb:
                    log(f"server footprint {g:.1f} GB > {args.cap_gb} GB: stopping")
                    peak["aborted"] = True
                    stop()
                    return
            stop_ev.wait(10)
    threading.Thread(target=watch, daemon=True).start()

    def body(prompt):
        return {"messages": [{"role": "user", "content": prompt}], **SAMPLING, "enable_thinking": False,
                "reasoning_effort": "none"}
    rows = [json.loads(l) for l in open(args.prompts)]
    if args.limit:
        rows = rows[:args.limit]
    done = set()
    gen_path = out / "generated.jsonl"
    if gen_path.exists():
        done = {json.loads(l)["id"] for l in open(gen_path)}
    try:
        t0 = time.time()
        end = time.time() + 1200
        while True:
            if proc.poll() is not None:
                raise SystemExit(f"server exited early ({proc.returncode})")
            try:
                if get(base, "/health").get("status") == "ok":
                    break
            except Exception:
                pass
            if time.time() > end:
                raise SystemExit("server not healthy after 20 min")
            time.sleep(3)
        rec["load_s"] = round(time.time() - t0, 1)
        st = get(base, "/v1/status")
        rec["status"] = {k: st.get(k) for k in ("model", "qualification", "settings")}
        log(f"{ckpt} healthy after {rec['load_s']}s")
        checks = []
        for r in rows[:3]:
            t = post(base, body(r["prompt"]))["choices"][0]["message"]["content"]
            why = garbled(t)
            checks.append({"id": r["id"], "garbled": why, "head": t[:240]})
            log(f"load check {r['id']}: {'OK' if not why else 'GARBLED ' + why} | {t[:120]!r}")
        rec["load_check"] = checks
        if any(c["garbled"] for c in checks):
            rec["aborted"] = "load check failed"
            raise SystemExit(4)
        todo = [r for r in rows if r["id"] not in done]
        n_ok = n_bad = 0
        with open(gen_path, "a") as gf, cf.ThreadPoolExecutor(args.lanes) as ex:
            futs = {ex.submit(post, base, body(r["prompt"])): r for r in todo}
            for i, fu in enumerate(cf.as_completed(futs)):
                r = futs[fu]
                try:
                    resp = fu.result()
                    t = resp["choices"][0]["message"]["content"]
                    why = garbled(t)
                except Exception as e:
                    t, why = "", f"request failed: {e}"
                row = {**{k: r[k] for k in ("id", "level", "register", "form", "theme")}, "text": t, "rejected": why,
                       "source": f"artemis:{r['id']}", "license": "model-generated by Artemis-31B-v1.2 (Gemma terms)",
                       "generator": ckpt, "sampling": SAMPLING}
                gf.write(json.dumps(row, ensure_ascii=False) + "\n")
                gf.flush()
                n_ok += why is None
                n_bad += why is not None
                if i % 50 == 0:
                    log(f"  {i + 1}/{len(todo)} ({time.time() - t0:.0f}s), rejected {n_bad}")
        rec.update({"generated": n_ok, "rejected": n_bad, "wall_s": round(time.time() - t0, 1)})
    finally:
        stop_ev.set()
        stop()
        rec["server_peak_footprint_gb"] = round(peak["gb"], 1)
        rec["server_aborted"] = peak.get("aborted", False)
        (out / "receipt.json").write_text(json.dumps(rec, indent=1) + "\n")
        log(f"receipt: {json.dumps({k: rec.get(k) for k in ('generated', 'rejected', 'wall_s', 'server_peak_footprint_gb')})}")


if __name__ == "__main__":
    main()
