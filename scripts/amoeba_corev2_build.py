#!/usr/bin/env python3
"""English core corpus v2: graded prose by education level x register, for carving nested cores
(Pierre, 2026-11-14): a grade-school core, an extended high-school core, a postgraduate/literary box,
expert tiles on top. Replaces repo_markdown as the carving corpus, so code-like topics stop being core
residents by construction. CPU only; no model is loaded.

Levels: L1 grade school, L2 high school, L3 postgraduate / literary.
Registers: narrative, expository, technical (code stripped), dialogue, instructions, letters, and the
literary forms poetry, drama (play / screenplay form) and song (lyrics; public domain only here; text
generated by Artemis-31B-v1.2 is added as its own source with --add-generated, see below).

Sources (provenance per text; see the manifest):
  local   cosmopedia-v2 shard (ODC-BY; audience x format labels), TinyStories (CDLA-Sharing-1.0), arXiv sample
          (CC0), NIST SP 800-53 / CWE prose (public domain / CWE ToU), BillSum (CC0)
  fetched PG-19 test+validation books and Gutenberg song books (public domain), Wikipedia + Simple Wikipedia
          leads (CC BY-SA 3.0), FineWeb-Edu sample shard (ODC-By; int_score), RFC prose (IETF Trust),
          Python tutorial (PSF)
Each text: ~400-1,200 characters, one window per source item; fit/held by sha256(group) parity; up to
--per-cell texts per (level, register) cell. Writes OUT/corpus.jsonl (research-artifacts, withheld) and the
manifest (git). The HF parquet shards are deleted after sampling (--delete-shards), as approved.

--add-generated GEN.jsonl --base CORPUS.jsonl (no resampling; the shards are gone): copies the base corpus
unchanged and appends every accepted generated text (scripts/amoeba_corev2_generate.py) trimmed to whole lines
of at most MAX chars (a text cut by max_tokens is long, so the cut falls past the trimmed window), split by
sha256(group) parity. Source 'artemis', label 'model-generated'; filter on source to exclude them.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import random
import re
import time
import zipfile
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HOME = Path.home()
ART = HOME / "Library/Application Support/mlx2/research-artifacts/amoeba"
COSMO = HOME / "mlx-training/hysparse2/public/HuggingFaceTB--smollm-corpus/3ba9d605774198c5868892d7a8deda78031a781f/cosmopedia-v2/train-00000-of-00104.parquet"
MIN, WIN, MAX = 400, 800, 1200
CODE = re.compile(r"```|^\s{4,}\S|[{};]\s*$|^\s*(def|class|import|for|if|return|#include)\b|>>>", re.M)


def sha(s):
    return hashlib.sha256(s.encode("utf-8", "replace")).hexdigest()


def clean_window(text, rng, start_frac=0.8):
    """A window of whole paragraphs, ~WIN chars, from a seeded start; None if too short."""
    paras = [p.strip() for p in re.split(r"\n\s*\n", text) if len(p.strip()) > 30]
    if not paras:
        return None
    for _ in range(4):
        i = rng.randrange(max(1, int(len(paras) * start_frac)))
        out, n = [], 0
        for p in paras[i:]:
            out.append(p)
            n += len(p)
            if n >= WIN:
                break
        w = "\n\n".join(out)[:MAX]
        if len(w) >= MIN:
            return w
    return None


def line_windows(body, rng, n=40, lines=28):
    """Windows of consecutive lines (verse and plays keep their shape), from n seeded starts."""
    L = body.splitlines()
    if len(L) < lines:
        return []
    out = []
    for _ in range(n):
        i = rng.randrange(len(L) - lines)
        w = "\n".join(L[i:i + lines]).strip()
        if len(w) >= MIN:
            out.append((i, w[:MAX]))
    return out


def gutenberg_body(t):
    a = re.search(r"\*\*\* ?START OF (THE|THIS) PROJECT GUTENBERG.*?\*\*\*", t)
    b = re.search(r"\*\*\* ?END OF (THE|THIS) PROJECT GUTENBERG", t)
    return t[a.end() if a else 0: b.start() if b else len(t)]


def classify_literary(w):
    """Register of a literary window by its shape: poetry (short lines), drama (speaker tags), letters,
    dialogue (many quoted lines), else narrative."""
    lines = [l for l in w.splitlines() if l.strip()]
    if not lines:
        return None
    short = sum(1 for l in lines if len(l.strip()) < 55) / len(lines)
    speakers = sum(1 for l in lines if re.match(r"^\s*[A-Z][A-Z .'-]{2,30}[.:]\s", l))
    if speakers >= 3:
        return "drama"
    if re.match(r"\s*(My )?(Dear|Dearest) [A-Z]", w) or re.search(r"\n\s*(Yours (truly|sincerely|faithfully|ever)|Your affectionate)", w):
        return "letters"
    if short > 0.75 and len(lines) >= 8:
        return "poetry"
    quotes = sum(1 for l in lines if l.strip().startswith(("\"", "“", "'")))
    if quotes >= 4:
        return "dialogue"
    return "narrative"


def trim_generated(t):
    """Whole lines up to MAX chars (blank trailing lines dropped). None if under MIN."""
    out, n = [], 0
    for ln in t.strip().splitlines():
        if n + len(ln) + 1 > MAX:
            break
        out.append(ln)
        n += len(ln) + 1
    w = "\n".join(out).strip()
    return w if len(w) >= MIN else None


def cells_of(items):
    cells = defaultdict(lambda: {"fit": 0, "held": 0, "sources": Counter(), "licenses": Counter()})
    for c in items:
        k = f"{c['level']}/{c['register']}"
        cells[k][c["split"]] += 1
        cells[k]["sources"][c["source"].split(":")[0]] += 1
        cells[k]["licenses"][c["license"]] += 1
    return {k: {"fit": v["fit"], "held": v["held"], "sources": dict(v["sources"]), "licenses": dict(v["licenses"])}
            for k, v in sorted(cells.items())}


def add_generated(args):
    out = Path(args.out)
    if out.exists() and any(out.iterdir()):
        raise SystemExit(f"refusing to overwrite {out}")
    gen = Path(args.add_generated)
    rec = json.loads((gen.parent / "receipt.json").read_text())
    base = [json.loads(l) for l in open(args.base)]
    items, dropped = list(base), Counter()
    for line in open(gen):
        g = json.loads(line)
        if g.get("rejected"):
            dropped["rejected"] += 1
            continue
        w = trim_generated(g["text"])
        if not w:
            dropped["under MIN chars after trim"] += 1
            continue
        group = f"artemis/{g['id']}"
        items.append({"level": g["level"], "register": g["register"], "text": w, "source": f"artemis:{g['id']}",
                      "group": group, "license": g["license"], "form": g["form"], "theme": g["theme"],
                      "generator": g["generator"], "label": "model-generated",
                      "split": "fit" if int(hashlib.sha256(group.encode()).hexdigest()[:8], 16) % 2 == 0 else "held",
                      "sha256": sha(w), "id": f"cg{len(items) - len(base):05d}"})
    out.mkdir(parents=True, exist_ok=True)
    with open(out / "corpus.jsonl", "w") as f:
        for c in items:
            f.write(json.dumps(c, ensure_ascii=False) + "\n")
    man = json.loads(Path(args.manifest).read_text())
    prev = {k: man[k] for k in ("corpus_path", "corpus_sha256", "items", "built")}
    man.pop("pending", None)
    man.update({"built": time.strftime("%Y-%m-%dT%H:%M:%S%z"), "corpus_path": str(out / "corpus.jsonl"),
                "corpus_sha256": hashlib.sha256((out / "corpus.jsonl").read_bytes()).hexdigest(), "items": len(items),
                "base": prev, "cells": cells_of(items)})
    man["generated"] = {"source": "artemis", "generator": rec["checkpoint"], "fingerprint": rec["fingerprint"],
                        "mlx2_source_revision": rec["mlx2_source_revision"], "sampling": rec["sampling"],
                        "thinking": rec["thinking"], "route": "ordinary, 4 lanes, unqualified", "approved": rec["approved"],
                        "generated_path": str(gen), "generated_sha256": hashlib.sha256(gen.read_bytes()).hexdigest(),
                        "prompts": "docs/research/amoeba-topics/core-corpus-v2-generation/prompts.jsonl",
                        "receipt": {k: rec.get(k) for k in ("generated", "rejected", "wall_s", "server_peak_footprint_gb", "load_s")},
                        "added": len(items) - len(base), "dropped": dict(dropped),
                        "trim": "whole lines <= 1200 chars",
                        "label": rec["label"], "withheld": "text stays in research-artifacts; never exported",
                        "note": "cells may exceed per_cell_target: generated texts fill the creative cells the "
                                "public-domain sources leave thin (letters, drama, L1/L3 song, L1/L2 poetry)"}
    Path(args.manifest).write_text(json.dumps(man, indent=1, ensure_ascii=False) + "\n")
    print(f"base {len(base)} + generated {len(items) - len(base)} = {len(items)}; dropped {dict(dropped)}")
    for k, v in man["cells"].items():
        print(f"  {k:22s} fit {v['fit']:4d} held {v['held']:4d}  {v['sources']}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--downloads", default=str(ART / "downloads/corev2-20261114"))
    ap.add_argument("--out", required=True)
    ap.add_argument("--manifest", default=str(ROOT / "docs/research/amoeba-topics/core-corpus-v2-manifest.json"))
    ap.add_argument("--per-cell", type=int, default=250)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--delete-shards", action="store_true")
    ap.add_argument("--add-generated", help="generated.jsonl from amoeba_corev2_generate.py (receipt.json beside it)")
    ap.add_argument("--base", help="existing corpus.jsonl to extend (with --add-generated)")
    args = ap.parse_args()
    if args.add_generated:
        if not args.base:
            raise SystemExit("--add-generated needs --base")
        return add_generated(args)
    import pyarrow.parquet as pq
    out = Path(args.out)
    if out.exists() and any(out.iterdir()):
        raise SystemExit(f"refusing to overwrite {out}")
    out.mkdir(parents=True, exist_ok=True)
    dl = Path(args.downloads)
    rng = random.Random(args.seed)
    cands = defaultdict(list)            # (level, register) -> items
    prov = {}

    def add(level, reg, text, source, group, lic):
        literary = source.startswith(("pg19:", "gutenberg:"))     # verse indents and ';' line ends are not code
        if text and len(text) >= MIN and not (reg != "technical" and not literary and CODE.search(text)):
            cands[(level, reg)].append({"level": level, "register": reg, "text": text[:MAX], "source": source,
                                        "group": group, "license": lic})

    # ---- Cosmopedia v2 (local; audience x format)
    AUD = {"young_children": "L1", "children": "L1", "middle_school_students": "L2", "high_school_studnets": "L2",
           "general": "L2", "college_students": "L3", "college_studnets": "L3", "researchers": "L3"}
    FMT = {"story": "narrative", "story_children": "narrative", "story_life_lessons": "narrative", "story_morality": "narrative",
           "story_reddit": "narrative", "story_forums": "narrative", "textbook": "expository",
           "textbook_unconditionned_topic": "expository", "textbook_narrative": "expository", "textbook_academic": "expository",
           "textbook_narrative_tone": "expository", "scientific_article": "expository", "dialogue": "dialogue",
           "wikihow": "instructions", "e-learning_module": "instructions"}
    if COSMO.exists():
        t = pq.read_table(COSMO, columns=["text", "audience", "format"])
        rows = list(zip(t.column("text").to_pylist(), t.column("audience").to_pylist(), t.column("format").to_pylist()))
        rng.shuffle(rows)
        per = Counter()
        for i, (text, aud, fmt) in enumerate(rows):
            lv, rg = AUD.get(aud), FMT.get(fmt)
            if not lv or not rg or per[(lv, rg, aud, fmt)] >= 600:
                continue
            per[(lv, rg, aud, fmt)] += 1
            add(lv, rg, clean_window(text, rng), f"cosmopedia-v2:{aud}/{fmt}", f"cosmo/{i}", "ODC-BY (cosmopedia-v2, smollm-corpus @3ba9d605)")
        prov["cosmopedia-v2"] = {"path": str(COSMO), "license": "ODC-BY", "synthetic": True}
        del rows, t
    # ---- TinyStories (local)
    hf = HOME / ".cache/huggingface/hub"
    tsl = sorted(hf.glob("datasets--roneneldan--TinyStories/snapshots/*/data/validation-*.parquet"))
    if tsl:
        for i, x in enumerate(pq.read_table(tsl[0], columns=["text"]).column("text").to_pylist()[:1500]):
            add("L1", "narrative", x if len(x) >= MIN else None, "tinystories:val", f"ts/{i}", "CDLA-Sharing-1.0 (TinyStories)")
    # ---- arXiv sample (local), BillSum, NIST/CWE (local downloads)
    ax = ART / "topic-arxiv-sample-e4c5fbd4/arxiv_sample.jsonl"
    if ax.exists():
        for line in open(ax):
            r = json.loads(line)
            add("L3", "expository", r["text"], f"arxiv:{r['primary']}", f"arxiv/{r['arxiv_id']}", "CC0-1.0 (arXiv metadata)")
    sec = ART / "downloads/sec-20261114"
    if (sec / "NIST_SP-800-53_rev5_catalog.json").exists():
        import sys
        sys.path.insert(0, str(ROOT / "scripts"))
        import amoeba_topics_corpus as TC
        for topics, text, src, group, lic in TC.sec_sources(sec):
            if src.startswith(("800-53:", "cwe:")):
                add("L3", "technical", text, src, group, lic)
    # ---- PG-19 + Gutenberg song books
    for f in sorted((dl / "pg19").glob("*.txt")):
        if f.name.endswith("_files.txt"):
            continue
        body = gutenberg_body(f.read_text(errors="replace"))
        kept = Counter()
        for i, w in line_windows(body, rng):
            w = re.sub(r"(?<!\n)\n(?!\n)(?=[a-z])", " ", w)          # re-join prose lines wrapped mid-sentence
            reg = classify_literary(w)
            if reg and kept[reg] < 2:
                kept[reg] += 1
                add("L3", reg, w, f"pg19:{f.stem}", f"pg19/{f.stem}/{reg}", "public domain (PG-19 / Project Gutenberg)")
    for f in sorted((dl / "gutenberg").glob("*.txt")):
        body = gutenberg_body(f.read_text(errors="replace"))
        lvl = "L1" if f.stem in ("pg27195", "pg21300") else "L2"           # folk rhymes and cowboy songs are plain
        for i, w in line_windows(body, rng, n=200, lines=24):
            if classify_literary(w) == "poetry":
                add(lvl, "song", w, f"gutenberg:{f.stem}", f"gut/{f.stem}/{i // 400}", "public domain (Project Gutenberg)")
    prov["pg19"] = {"lists": "deepmind/pg19 @4d28bd77e669 test+validation", "texts": "storage.googleapis.com/deepmind-gutenberg",
                    "license": "public domain texts; PG-19 Apache-2.0"}
    prov["gutenberg_songs"] = {"ids": [44969, 47692, 62474, 63116, 20476, 20604, 21300, 27195], "license": "public domain"}
    # ---- RFC prose
    for f in sorted((dl / "rfc").glob("rfc*.txt")):
        t = f.read_text(errors="replace")
        t = re.sub(r"\f.*?\n.*?\n", "\n", t)                           # page breaks and headers
        paras = [p for p in re.split(r"\n\s*\n", t) if len(p) > 200 and not re.search(r"[+|]-{3,}|-{3,}\+|::=|^\s{8,}\S", p, re.M)]
        rng.shuffle(paras)
        for k, p in enumerate(paras[:4]):
            add("L3", "technical", " ".join(p.split()), f"rfc:{f.stem}", f"rfc/{f.stem}", "IETF Trust (RFC text, reproduced with attribution)")
    # ---- Python tutorial (code stripped)
    z = next((dl / "python").glob("*.zip"), None)
    if z:
        with zipfile.ZipFile(z) as zf:
            for name in sorted(n for n in zf.namelist() if "/tutorial/" in n and n.endswith(".txt")):
                t = zf.read(name).decode("utf-8", "replace")
                paras = [p for p in re.split(r"\n\s*\n", t) if len(p) > 150 and not CODE.search(p) and not p.lstrip().startswith(("*", "="))]
                for k, p in enumerate(paras):
                    add("L2", "technical", " ".join(p.split()), f"python-tutorial:{Path(name).stem}", f"pytut/{Path(name).stem}/{k // 3}",
                        "PSF License (Python documentation)")
    # ---- Wikipedia leads; FineWeb-Edu by int_score
    for f, lvl in ((dl / "hf/wiki-simple-00000.parquet", "L1"), (dl / "hf/wiki-en-00000.parquet", "L2")):
        if f.exists():
            t = pq.read_table(f, columns=["title", "text"])
            n = 0
            for title, text in zip(t.column("title").to_pylist(), t.column("text").to_pylist()):
                lead = text.split("\n\n")[0] if text else ""
                if len(lead) >= MIN and n < 2500:
                    n += 1
                    add(lvl, "expository", lead, f"wikipedia:{f.stem}", f"wiki/{f.stem}/{title}", "CC BY-SA 3.0 (Wikipedia)")
            prov[f.stem] = {"dataset": "wikimedia/wikipedia @b04c8d1ceb2f", "license": "CC BY-SA 3.0 / GFDL", "sha256": None}
    fw = dl / "hf/fineweb-edu-10BT-000_00000.parquet"
    if fw.exists():
        pf = pq.ParquetFile(fw)
        n = Counter()
        for b in pf.iter_batches(batch_size=20000, columns=["text", "int_score", "id"]):
            for text, sc, i in zip(b.column("text").to_pylist(), b.column("int_score").to_pylist(), b.column("id").to_pylist()):
                lvl = "L2" if sc in (2, 3) else "L3" if sc and sc >= 4 else None
                if lvl and n[lvl] < 2500:
                    n[lvl] += 1
                    add(lvl, "expository", clean_window(text, rng), f"fineweb-edu:int{sc}", f"fwe/{i}", "ODC-By (FineWeb-Edu)")
            if min(n.values(), default=0) >= 2500 and len(n) == 2:
                break
        prov["fineweb-edu"] = {"dataset": "HuggingFaceFW/fineweb-edu @87f09149ef47 sample/10BT/000_00000", "license": "ODC-By"}
    for f in (dl / "hf").glob("*.parquet"):
        prov.setdefault("shard_sha256", {})[f.name] = hashlib.sha256(f.read_bytes()).hexdigest()
    # ---- select per cell, split by group
    items = []
    for cell, cs in sorted(cands.items()):
        seen = set()
        cs = [c for c in cs if not (c["text"] in seen or seen.add(c["text"]))]
        random.Random(f"{args.seed}:{cell}").shuffle(cs)
        taken, per_group = Counter(), Counter()
        for c in cs:
            sp = "fit" if int(hashlib.sha256(c["group"].encode()).hexdigest()[:8], 16) % 2 == 0 else "held"
            if taken[sp] >= args.per_cell // 2 or per_group[c["group"]] >= 2:
                continue
            taken[sp] += 1
            per_group[c["group"]] += 1
            c["split"] = sp
            c["sha256"] = sha(c["text"])
            items.append(c)
    for i, c in enumerate(items):
        c["id"] = f"cc{i:05d}"
    with open(out / "corpus.jsonl", "w") as f:
        for c in items:
            f.write(json.dumps(c, ensure_ascii=False) + "\n")
    cells = defaultdict(lambda: {"fit": 0, "held": 0, "sources": Counter(), "licenses": Counter()})
    for c in items:
        k = f"{c['level']}/{c['register']}"
        cells[k][c["split"]] += 1
        cells[k]["sources"][c["source"].split(":")[0]] += 1
        cells[k]["licenses"][c["license"]] += 1
    man = {"schema": "mlx2.amoeba-core-corpus.v2", "built": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
           "builder": "scripts/amoeba_corev2_build.py", "corpus_path": str(out / "corpus.jsonl"),
           "corpus_sha256": hashlib.sha256((out / "corpus.jsonl").read_bytes()).hexdigest(), "items": len(items),
           "per_cell_target": args.per_cell, "levels": {"L1": "grade school", "L2": "high school", "L3": "postgraduate / literary"},
           "registers": ["narrative", "expository", "technical (code stripped)", "dialogue", "instructions", "letters",
                         "poetry", "drama", "song"],
           "approved": "Pierre 2026-11-14 ('Approve all seven'); Cosmopedia downloads skipped (local cosmopedia-v2 shard used)",
           "pending": "creative text (lyrics, poetry, screenplay) generated by Artemis-31B-v1.2: separate GPU window, needs approval",
           "topic_recognition_hook": "use the topic probe corpus v4 held split (docs/research/amoeba-topics/probe-corpus-manifest.json) "
                                     "to measure gate recognition from core hidden states",
           "rules": {"split": "sha256(group) parity", "window_chars": [MIN, MAX], "code": "texts with code markers dropped outside 'technical'"},
           "provenance": prov,
           "cells": {k: {"fit": v["fit"], "held": v["held"], "sources": dict(v["sources"]), "licenses": dict(v["licenses"])}
                     for k, v in sorted(cells.items())}}
    Path(args.manifest).write_text(json.dumps(man, indent=1, ensure_ascii=False) + "\n")
    if args.delete_shards:
        for f in (dl / "hf").glob("*.parquet"):
            f.unlink()
    print(f"wrote {len(items)} items over {len(cells)} cells")
    for k, v in sorted(cells.items()):
        print(f"  {k:22s} fit {v['fit']:4d} held {v['held']:4d}  {dict(v['sources'])}")


if __name__ == "__main__":
    main()
