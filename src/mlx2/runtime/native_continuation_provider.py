"""Model-neutral adapter contract for native continuation lifecycle ownership."""

from __future__ import annotations

from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class NativeContinuationProvider(Protocol):
    revision: str
    protocol: str
    candidate_type: type

    def validate_candidate(self, candidate: Any) -> None: ...
    def create_continuation(self, **kwargs: Any) -> Any: ...
    def probe(self, *args: Any, candidate: Any, **kwargs: Any) -> Any: ...
    def prepare(self, *args: Any, **kwargs: Any) -> Any: ...
    def run_research(self, *args: Any, candidate: Any, **kwargs: Any) -> Any: ...
    def run_research_pair(
        self, *args: Any, candidate: Any, **kwargs: Any
    ) -> Any: ...
    def receipt(self) -> dict: ...
