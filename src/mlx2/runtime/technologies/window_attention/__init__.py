"""Dense softmax attention with windows: masks, reference, fast-path registry.

One technology covers every dense (non-MLA, non-sparse-selection) softmax
attention over a K/V view whose visible keys are bounded by a causal window:
full causal attention, sliding windows, a retained sink prefix
(``RotatingKVCache(keep=...)``, ``SinkWindowKVCache``), rotating ring caches,
learned per-head sink logits and logit soft-capping.

* :class:`WindowAttentionSpec` -- every per-model parameter, with
  :meth:`WindowAttentionSpec.from_config` deriving it from HF configs
  (``sliding_window``, ``layer_types``, ``sliding_window_pattern``,
  ``hybrid_layer_pattern``, ``attn_logit_softcapping``,
  ``query_pre_attn_scalar``, ``num_sink_tokens``, ...).
* Masks (pure MLX, integer/bool logic, so equal by construction across the
  copies they replace): :func:`window_keep`, :func:`causal_window_mask`,
  :func:`sink_prefix_window_mask`, :func:`ring_decode_window_mask`,
  :func:`additive_mask`.
* :func:`reference_attention` -- the composed MLX attention (GQA repeat,
  scale, optional soft-cap, float32 softmax with an optional sink column).
* Fast paths: :data:`DENSE` (``window_attention.dense``) registers the opt-in
  float kernels ``models.base.scaled_dot_product_attention`` may take ahead
  of stock ``mx.fast.scaled_dot_product_attention``; the window-row kernels
  and the quantized-KV kernels are listed in :data:`FAST_PATHS` with their
  admission functions.  The Metal text of every vector-SDPA transcription is
  generated by :mod:`.vector_sources` (byte-identical to the legacy copies).

See docs/technologies/window_attention.md.
"""

