def _layer_windowed(config) -> Optional[tuple]:
    """Which layers are windowed, from whichever field the config uses."""

    def get(key):
        if isinstance(config, dict):
            return config.get(key)
        return getattr(config, key, None)

    types = get("layer_types")
    if types:
        return tuple(str(t) in ("sliding_attention", "sliding", "local", "swa") for t in types)
    pattern = get("hybrid_layer_pattern")
    if pattern is not None:  # MiMo: 1 = sliding window
        return tuple(bool(int(p)) for p in pattern)
    n = get("num_hidden_layers")
    every = get("sliding_window_pattern")
    if every is None:
        every = get("hybrid_block_size")  # MiMo's block form: every b-th layer full
    if isinstance(every, int) and every > 0 and isinstance(n, int):
        # Gemma 3 / MiMo convention: layer i is full iff (i + 1) % every == 0.
        return tuple((i + 1) % every != 0 for i in range(n))
    return None


def _scale(config):
    get = (config.get if isinstance(config, dict) else lambda k: getattr(config, k, None))
    qpas = get("query_pre_attn_scalar")
    if qpas:
        return float(qpas) ** -0.5
    head_dim = get("head_dim")
    if not head_dim and get("hidden_size") and get("num_attention_heads"):
        head_dim = get("hidden_size") // get("num_attention_heads")
    return float(head_dim) ** -0.5 if head_dim else None


@dataclass(frozen=True)
class WindowAttentionSpec:
    """Per-model parameters of dense windowed softmax attention.

    Window convention: a query at position ``q`` sees key position ``k``
    when ``k <= q`` and ``q - k < sliding_window`` (``window_counts_query``:
    the window counts the query itself, as MLX's ``create_causal_mask`` and
    every sliding-window model here do).  ``window_counts_query=False`` is
    ``SinkWindowKVCache``'s convention: ``sliding_window`` keys *before* the
    query, i.e. ``k >= q - sliding_window``.
    """

    # Keys visible to a windowed layer (None: full causal attention).
    sliding_window: Optional[int] = None
    # Per layer: True when the layer is windowed (None: every layer is
    # windowed iff ``sliding_window`` is set).
    layer_windowed: Optional[tuple] = None
    window_counts_query: bool = True
    # Leading positions always visible (a retained sink prefix).
    sink_tokens: int = 0
    # A learned per-head sink logit joins the softmax (gpt-oss, MiMo SWA).
    sink_logits: bool = False
    # ``tanh(s / cap) * cap`` on the float32 scores before masking.
    logit_softcap: Optional[float] = None
    # Score scale (None: head_dim ** -0.5 at call time).
    scale: Optional[float] = None
    # How an explicit mask reaches the scores: a bool ``keep`` array or an
    # additive float32 array (0 / -inf).
    mask_form: str = "bool"

    def __post_init__(self):
        if self.mask_form not in ("bool", "additive"):
            raise ValueError(f"mask_form must be 'bool' or 'additive'; got {self.mask_form!r}")
        if self.sliding_window is not None and int(self.sliding_window) < 1:
            raise ValueError("sliding_window must be >= 1")
        if self.sink_tokens < 0:
            raise ValueError("sink_tokens must be >= 0")

    @classmethod
    def from_config(cls, config: Any, **overrides) -> "WindowAttentionSpec":
        return spec_from_config(
            cls,
            config,
            {
                "sliding_window": ("sliding_window", "sliding_window_size", "attention_window"),
                "layer_windowed": _layer_windowed,
                "sink_tokens": ("num_sink_tokens", "attention_sink_size", "sink_size"),
                "sink_logits": ("add_swa_attention_sink_bias", "attention_sinks"),
                "logit_softcap": "attn_logit_softcapping",
                "scale": _scale,
            },
            **overrides,
        )

    def window_for_layer(self, layer: int) -> Optional[int]:
        """The layer's window, or None for a full-attention layer."""
        if self.sliding_window is None:
            return None
        if self.layer_windowed is None:
            return int(self.sliding_window)
        return int(self.sliding_window) if self.layer_windowed[layer] else None


