# Reference attention
# --------------------------------------------------------------------------


def reference_attention(
    queries: mx.array,
    keys: mx.array,
    values: mx.array,
    spec: WindowAttentionSpec,
    *,
    mask: Optional[mx.array] = None,
    sinks: Optional[mx.array] = None,
    row_chunk: Optional[int] = None,
    probs_dtype=None,
) -> mx.array:
    """``[B, H, L, Dv]``: composed softmax attention.

    ``queries [B, H, L, D]``, ``keys [B, KVH, N, D]``, ``values [B, KVH, N,
    Dv]`` (KV heads repeated to H).  Scores ``(q @ k^T) * scale`` in the
    input dtype, then float32 (soft-capped when ``spec.logit_softcap``) plus
    ``mask`` (``spec.mask_form``: additive float32 rows ``[L, N]`` /
    broadcastable, or bool keep), a per-head ``sinks`` logit column when
    given, ``softmax(s - max(s))`` rounded to the input dtype, the sink
    column dropped, times ``values``.  ``row_chunk`` evaluates query rows in
    chunks (same arithmetic per row).  ``probs_dtype`` is the dtype the
    probabilities are rounded to (default ``queries.dtype``).
    """
    B, H, L, D = queries.shape
    groups = H // keys.shape[1]
    if groups > 1:
        keys = mx.repeat(keys, groups, axis=1)
        values = mx.repeat(values, groups, axis=1)
    scale = spec.scale if spec.scale is not None else D ** -0.5
    if mask is not None and spec.mask_form == "bool":
        mask = additive_mask(mask)
    step = row_chunk or L
    outs = []
    for r0 in range(0, L, step):
        r1 = min(L, r0 + step)
        s = (queries[:, :, r0:r1] @ keys.transpose(0, 1, 3, 2)) * scale
        s = s.astype(mx.float32)
        if spec.logit_softcap is not None:
            cap = float(spec.logit_softcap)
            s = mx.tanh(s / cap) * cap
        if mask is not None:
            s = s + (mask[..., r0:r1, :] if mask.ndim >= 2 and mask.shape[-2] == L else mask)
        if sinks is not None:
            col = mx.broadcast_to(sinks.astype(mx.float32).reshape(1, -1, 1, 1), (B, H, r1 - r0, 1))
            s = mx.concatenate([s, col], axis=-1)
        p = mx.softmax(s - mx.max(s, axis=-1, keepdims=True), axis=-1).astype(
            queries.dtype if probs_dtype is None else probs_dtype
        )
        if sinks is not None:
            p = p[..., :-1]
        outs.append(p @ values)
    return outs[0] if len(outs) == 1 else mx.concatenate(outs, axis=2)


