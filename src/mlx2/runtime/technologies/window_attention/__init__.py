# Opt-in selections of the float fast paths ``DENSE`` dispatches.
_DENSE_ENV = ("MLX2_FP_VERIFY_KERNEL", "MLX2_SDPA_D512_TK2", "MLX2_FP_DECODE_KERNEL")


def dense_fast_paths_requested() -> bool:
    """Whether any opt-in float fast path is selected.  ``models.base``
    inlines the cheaper shape-first form of this gate on its hot path."""
    return any(os.environ.get(name, "0") == "1" for name in _DENSE_ENV)


def _stock(queries, keys, values, *, scale, mask=None, sinks=None):
    from ...models.base import fast_sdpa

    return fast_sdpa(queries, keys, values, scale=scale, mask=mask, sinks=sinks)


def _admit_fp_verify(spec, *, queries, keys, values, mask=None, sinks=None):
    if not 2 <= queries.shape[2] <= 16:
        return "geometry: fp_verify serves 2-16 query rows"
    from ...models.fp_verify_tensor import use_kernel

    if not use_kernel(queries, keys, values, mask, sinks):
        return "not_admitted: MLX2_FP_VERIFY_KERNEL off, geometry or device"
    return None


def _run_fp_verify(queries, keys, values, *, scale, mask=None, sinks=None):
    from ...models.fp_verify_tensor import attention

    return attention(queries, keys, values, scale=scale, mask=mask, sinks=sinks)


def _admit_d512(spec, *, queries, keys, values, mask=None, sinks=None):
    if queries.shape[2] != 1 or queries.shape[-1] != 512 or sinks is not None:
        return "geometry: one row, head dim 512, no sinks"
    from ...models import sdpa_vector_d512 as d512

    if not d512.use_kernel(queries, keys, values, mask=mask):
        return "not_admitted: MLX2_SDPA_D512_TK2 off or geometry stock MLX would not vectorise"
    return None


def _run_d512(queries, keys, values, *, scale, mask=None, sinks=None):
    from ...models import sdpa_vector_d512 as d512

    return d512.attention(queries, keys, values, scale=scale)


def _row_mask(mask):
    return None if isinstance(mask, str) else mask


def _admit_fp_decode(spec, *, queries, keys, values, mask=None, sinks=None):
    if queries.shape[2] != 1 or sinks is not None:
        return "geometry: one row, no sinks"
    from ...models.qsdpa_decode_metal import use_fp_decode_kernel

    if not use_fp_decode_kernel(queries, keys, values, mask=_row_mask(mask)):
        return "not_admitted: MLX2_FP_DECODE_KERNEL off, geometry or context"
    return None


def _run_fp_decode(queries, keys, values, *, scale, mask=None, sinks=None):
    from ...models.qsdpa_decode_metal import gqa_decode_attention_fp

    return gqa_decode_attention_fp(queries, keys, values, scale=scale, mask=_row_mask(mask))


# ``models.base.scaled_dot_product_attention``'s unquantized branch, in its
# historical order; the fallback is stock MLX SDPA (the ordinary path).
DENSE = KernelRegistry(f"{TECHNOLOGY}.dense", _stock)
DENSE.register(FastPath("fp_verify_tensor", _admit_fp_verify, _run_fp_verify))
DENSE.register(FastPath("sdpa_vector_d512_tk2", _admit_d512, _run_d512))
DENSE.register(FastPath("qsdpa_fp_decode", _admit_fp_decode, _run_fp_decode))


